#!/usr/bin/env python3
"""Generate Codex adapters and bridge shared studio helpers (Python 3.11+)."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[2]
MARKER = "Generated by scripts/codex/studio.py"
MANIFEST = Path(".codex/studio-manifest.json")


def frontmatter(path: Path) -> tuple[dict[str, str], str]:
    """Read the scalar fields used by this adapter; reject unsupported forms."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not match:
        raise ValueError(f"Missing frontmatter: {path}")
    values = {}
    for key in ("name", "description"):
        field = re.search(rf"^{key}:\s*(.+)$", match[1], re.M)
        if not field:
            raise ValueError(f"Missing {key}: {path}")
        value = field[1].strip()
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        elif value in ("|", ">", "|-", ">-"):
            raise ValueError(f"Multiline {key} needs explicit support: {path}")
        values[key] = value
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", values["name"]):
        raise ValueError(f"Invalid name: {path}")
    return values, match[2]


def source_skill(root: Path, name: str) -> Path:
    name = name.removeprefix("studio-")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
        raise ValueError("Invalid skill name")
    path = root / ".claude/skills" / name / "SKILL.md"
    if not path.is_file():
        raise ValueError(f"Unknown studio skill: {name}")
    return path


def context_commands(root: Path, skill: Path) -> list[tuple[list[str], int | None]]:
    """Translate known read-only directives. Never run arbitrary Markdown code."""
    result = []
    source = skill.read_text()
    directives = re.findall(r"^!`(.*)`[ \t]*$", source, re.M)
    if len(directives) != len(re.findall(r"^!`", source, re.M)):
        raise ValueError(f"Unsupported multiline context directive in {skill}")
    for raw in directives:
        expanded = raw.replace("${CLAUDE_SKILL_DIR}", str(skill.parent))
        config = re.fullmatch(
            r'bash "[^"\n]+/../../hooks/yaml-helper.sh" resolve_config --keys ([a-zA-Z0-9_.,-]+)',
            expanded,
        )
        if config:
            result.append((["bash", str(root / ".claude/hooks/yaml-helper.sh"),
                            "resolve_config", "--keys", config[1]], None))
        elif raw == 'bash "${CLAUDE_SKILL_DIR}/../../scripts/story-status.sh"':
            result.append((["bash", str(root / ".claude/scripts/story-status.sh")], None))
        elif raw == "git log --oneline -30 2>/dev/null || true":
            result.append((["git", "log", "--oneline", "-30"], None))
        elif raw == "git tag --list --sort=-v:refname 2>/dev/null | head -5":
            result.append((["git", "tag", "--list", "--sort=-v:refname"], 5))
        elif raw == 'ls production/sprints/ 2>/dev/null || echo "(no production/sprints/ directory yet)"':
            result.append((["@sprints"], None))
        else:
            raise ValueError(f"Unsupported context directive in {skill}: {raw}")
    return result


def generated(root: Path) -> dict[Path, str]:
    outputs = {}
    skills = sorted((root / ".claude/skills").glob("*/SKILL.md"))
    agents = sorted((root / ".claude/agents").glob("*.md"))
    if not skills or not agents:
        raise ValueError("Shared skills and agent sources are required")
    for source in skills:
        meta, _ = frontmatter(source)
        name = meta["name"]
        if source.parent.name != name:
            raise ValueError(f"Skill name/directory mismatch: {source}")
        context_commands(root, source)
        port = f"studio-{name}"
        if len(port) >= 64:
            raise ValueError(f"Codex skill name too long: {port}")
        outputs[Path(f".agents/skills/{port}/SKILL.md")] = f'''---
name: {port}
description: {json.dumps("Game development: " + meta["description"], ensure_ascii=False)}
---

<!-- {MARKER}; edit the generator, then sync. -->

# Studio: {name}

1. Read the [Codex runtime guide](../../../docs/codex/runtime.md) once per session.
2. From the repository root, run `python3 scripts/codex/studio.py context {name}`.
3. Read the [shared workflow](../../../.claude/skills/{name}/SKILL.md) and follow
   its body using that context and the runtime translations. Read its supporting
   references only when the current phase needs them.

Use the text after `${port}` as the workflow arguments. References such as
`references/example.md` in the shared workflow are relative to
`.claude/skills/{name}/`, not this adapter. Shared `/NAME` workflow commands
become `$studio-NAME`; Claude model/tool frontmatter does not configure Codex.
Use existing user decisions and authorization; ask only for unresolved choices.
'''
    for source in agents:
        meta, _ = frontmatter(source)
        name = meta["name"]
        if source.stem != name:
            raise ValueError(f"Agent name/file mismatch: {source}")
        instruction = (
            f"Act as the studio's {name} for the assigned task. Read docs/codex/runtime.md "
            f"and the body of .claude/agents/{name}.md from the repository root. "
            "Apply the runtime translations; upstream model, tools, skills and memory "
            "frontmatter are not Codex configuration. Read relevant supporting references "
            "on demand. Follow applicable AGENTS.md, task scope, file ownership and the "
            "parent's existing authorization. Report evidence, changed files and unresolved "
            "questions. Do not claim a test, launch or delegation happened without evidence."
        )
        outputs[Path(f".codex/agents/studio-{name}.toml")] = (
            f"# {MARKER}; edit the generator, then sync.\n"
            f"name = {json.dumps('studio-' + name)}\n"
            f"description = {json.dumps(meta['description'], ensure_ascii=False)}\n"
            f"developer_instructions = {json.dumps(instruction)}\n"
        )
    # Preserve upstream directory instructions without duplicating their bodies.
    scoped = sorted(p for p in root.glob("*/CLAUDE.md") if p.is_file())
    for source in scoped:
        rel = source.parent.relative_to(root)
        outputs[rel / "AGENTS.md"] = f'''<!-- {MARKER}; edit the generator, then sync. -->
# Codex instructions for {rel.as_posix()}

Read `CLAUDE.md` in this directory for the shared domain standards, interpreted
through the root `docs/codex/runtime.md`. Use `$studio-NAME` for studio workflows.
Explicit user decisions and authorization take precedence over repeated
approval prompts. Resolve rigor before applying design or QA requirements.
'''
    # Only shared framework sources participate; runtime memories, logs and
    # nested worktrees must never enter the generated manifest's digest.
    sources = sorted(p for folder in ("skills", "agents", "docs", "rules", "hooks", "scripts")
                     for p in (root / ".claude" / folder).rglob("*") if p.is_file()
                     and "__pycache__" not in p.parts)
    digest = hashlib.sha256()
    for path in sources + scoped:
        digest.update(path.relative_to(root).as_posix().encode())
        digest.update(b"\0" + path.read_bytes() + b"\0")
    manifest = {
        "format": 1,
        "generator": "scripts/codex/studio.py",
        "upstream": "https://github.com/Donchitos/Claude-Code-Game-Studios",
        "shared_source_digest": digest.hexdigest(),
        "skills": len(skills), "agents": len(agents),
        "generated_files": [p.as_posix() for p in sorted(outputs)],
    }
    outputs[MANIFEST] = json.dumps(manifest, indent=2) + "\n"
    return outputs


def sync(root: Path, check: bool = False) -> int:
    expected = generated(root)
    stale = []
    manifest_path = root / MANIFEST
    if manifest_path.exists():
        for rel in json.loads(manifest_path.read_text()).get("generated_files", []):
            path = (root / rel).resolve()
            if not path.is_relative_to(root.resolve()):
                raise ValueError("Manifest path escapes repository")
            if Path(rel) not in expected and path.is_file():
                stale.append(path)
    errors = []
    for rel, content in expected.items():
        path = root / rel
        if path.is_file() and path.read_text() == content:
            continue
        if check:
            errors.append(f"Out of date: {rel}")
        else:
            if path.exists() and rel != MANIFEST and MARKER not in path.read_text():
                raise ValueError(f"Refusing to overwrite non-generated file: {rel}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for path in stale:
        if check:
            errors.append(f"Stale generated file: {path.relative_to(root)}")
        elif MARKER in path.read_text():
            path.unlink()
        else:
            raise ValueError(f"Refusing to remove non-generated file: {path}")
    if check:
        for rel in expected:
            path = root / rel
            if not path.exists():
                continue
            if rel.name == "SKILL.md":
                frontmatter(path)
                for target in re.findall(r"\]\(([^)]+)\)", path.read_text()):
                    if not (path.parent / target).is_file():
                        errors.append(f"Broken link in {rel}: {target}")
            elif rel.suffix == ".toml":
                data = tomllib.loads(path.read_text())
                if set(data) != {"name", "description", "developer_instructions"}:
                    errors.append(f"Unexpected native agent configuration: {rel}")
        if not (root / "docs/codex/runtime.md").is_file():
            errors.append("Missing runtime guide")
        for path, patterns in rule_index(root):
            if not patterns:
                errors.append(f"Rule has no paths: {path}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    info = json.loads(expected[MANIFEST])
    print(f"{'Checked' if check else 'Synced'} {info['skills']} skills, {info['agents']} agents")
    return 0


def run(root: Path, command: list[str], skill: Path | None = None, **kwargs):
    env = os.environ.copy()
    env["CLAUDE_PROJECT_DIR"] = str(root)
    if skill:
        env["CLAUDE_SKILL_DIR"] = str(skill.parent)
    return subprocess.run(command, cwd=root, env=env, text=True, **kwargs)


def context(root: Path, name: str) -> int:
    skill = source_skill(root, name)
    commands = context_commands(root, skill)
    if not commands:
        print("No injected context; follow the workflow's explicit project reads.")
    for argv, limit in commands:
        print(f"\n$ {shlex.join(argv)}", flush=True)
        if argv == ["@sprints"]:
            folder = root / "production/sprints"
            print("\n".join(p.name for p in sorted(folder.iterdir())) if folder.is_dir()
                  else "(no production/sprints/ directory yet)")
            continue
        result = run(root, argv, skill, capture_output=True)
        output = result.stdout
        if limit:
            output = "\n".join(output.splitlines()[:limit]) + "\n"
        print(output, end="")
        if result.stderr:
            print(result.stderr, end="", file=sys.stderr)
        if result.returncode and argv[:2] == ["git", "log"]:
            # The shared directive explicitly ends in `|| true`; a new
            # game repository can legitimately have no commit history yet.
            print("(Commit history unavailable; continuing as the shared workflow specifies.)")
        elif result.returncode:
            return result.returncode
    return 0


def helper(root: Path, name: str, script: str, arguments: list[str]) -> int:
    skill = source_skill(root, name)
    path = (root / ".claude" / script).resolve()
    allowed = [(root / ".claude" / part).resolve() for part in ("hooks", "scripts")]
    if not any(path.is_relative_to(p) for p in allowed) or path.suffix != ".sh" or not path.is_file():
        raise ValueError("Helper must be an existing .sh file inside .claude/hooks or .claude/scripts")
    return run(root, ["bash", str(path), *arguments], skill).returncode


def expand_braces(pattern: str) -> list[str]:
    match = re.search(r"\{([^{}]+)\}", pattern)
    if not match:
        return [pattern]
    return [p for part in match[1].split(",") for p in
            expand_braces(pattern[:match.start()] + part + pattern[match.end():])]


def glob_matches(path: str, pattern: str) -> bool:
    # **/ includes zero directories; * never crosses a directory boundary.
    for expanded in expand_braces(pattern):
        regex = ""
        i = 0
        while i < len(expanded):
            if expanded[i:i + 3] == "**/":
                regex += "(?:.*/)?"; i += 3
            elif expanded[i:i + 2] == "**":
                regex += ".*"; i += 2
            elif expanded[i] == "*":
                regex += "[^/]*"; i += 1
            elif expanded[i] == "?":
                regex += "[^/]"; i += 1
            else:
                regex += re.escape(expanded[i]); i += 1
        if re.fullmatch(regex, path):
            return True
    return False


def rule_index(root: Path) -> list[tuple[Path, list[str]]]:
    rules = []
    for path in sorted((root / ".claude/rules").glob("*.md")):
        text = path.read_text()
        head = text.split("---", 2)[1] if text.startswith("---\n") else ""
        patterns = [line.strip().strip('"\'') for line in re.findall(r"^\s+-\s+(.+)$", head, re.M)]
        rules.append((path, patterns))
    return rules


def relative_file(root: Path, value: str) -> str:
    path = Path(value)
    path = (path if path.is_absolute() else root / path).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError(f"Path is outside this studio: {value}")
    return path.relative_to(root.resolve()).as_posix()


def rules(root: Path, paths: list[str]) -> int:
    paths = [relative_file(root, path) for path in paths]
    for rule, patterns in rule_index(root):
        matches = [p for p in paths if any(glob_matches(p, pattern) for pattern in patterns)]
        if matches:
            print(f"{rule.relative_to(root)}\t{', '.join(matches)}")
    return 0


def validate(root: Path, kind: str, paths: list[str]) -> int:
    if kind == "assets" and not paths:
        raise ValueError("assets validation needs at least one file path")
    if kind != "assets" and paths:
        raise ValueError("Only assets validation accepts file paths")
    events = []
    if kind == "assets":
        for value in paths:
            rel = relative_file(root, value)
            if not (root / rel).is_file():
                raise ValueError(f"Missing asset: {rel}")
            if rel.split('/')[0] not in ("assets", "Assets", "Content"):
                raise ValueError(f"Not an engine asset path: {rel}")
            events.append({"tool_name": "Write", "tool_input": {"file_path": rel}})
    else:
        events.append({"tool_name": "Bash", "tool_input": {"command": f"git {kind}"}})
    status = 0
    for event in events:
        result = run(root, ["bash", str(root / f".claude/hooks/validate-{kind}.sh")],
                     input=json.dumps(event))
        status = max(status, result.returncode)
    return status


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("sync")
    commands.add_parser("check")
    ctx = commands.add_parser("context"); ctx.add_argument("skill")
    hp = commands.add_parser("helper"); hp.add_argument("skill"); hp.add_argument("script")
    hp.add_argument("arguments", nargs=argparse.REMAINDER)
    rp = commands.add_parser("rules"); rp.add_argument("paths", nargs="+")
    vp = commands.add_parser("validate"); vp.add_argument("kind", choices=["commit", "push", "assets"])
    vp.add_argument("paths", nargs="*")
    args = parser.parse_args()
    try:
        if args.command in ("sync", "check"):
            return sync(ROOT, check=args.command == "check")
        if args.command == "context": return context(ROOT, args.skill)
        if args.command == "helper": return helper(ROOT, args.skill, args.script, args.arguments)
        if args.command == "rules": return rules(ROOT, args.paths)
        return validate(ROOT, args.kind, args.paths)
    except (ValueError, OSError, KeyError) as exc:
        print(f"studio: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
